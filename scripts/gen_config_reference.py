"""Generate the config reference in docs/implementation-guide.md from the shipped JSON Schema.

The table lives between the BEGIN/END markers below. `--check` exits 1 if the guide is
stale (run by `make verify`); without it the guide is rewritten in place.

    uv run python scripts/gen_config_reference.py [--check] [--guide PATH]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "src" / "dbt_agents_schema" / "schemas" / "agents_schema.schema.json"
GUIDE = ROOT / "docs" / "implementation-guide.md"
BEGIN = "<!-- BEGIN CONFIG REFERENCE (generated by scripts/gen_config_reference.py) -->"
END = "<!-- END CONFIG REFERENCE -->"


def _resolve(node: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    """Merge a `$ref` target under the node's own annotations."""
    if "$ref" not in node:
        return node
    target = defs[node["$ref"].rsplit("/", 1)[1]]
    return {**target, **{k: v for k, v in node.items() if k != "$ref"}}


def _type(node: dict[str, Any]) -> str:
    if "const" in node:
        return f"`{json.dumps(node['const'])}`"
    if "enum" in node:
        return " \\| ".join(f"`{v}`" for v in node["enum"])
    kind = node.get("type", "")
    if kind == "array":
        return f"list of {node.get('items', {}).get('type', 'any')}"
    if kind == "object":
        return "mapping"
    return str(kind)


def _default(node: dict[str, Any], required: bool) -> str:
    if required:
        return "required"
    if "default" in node:
        return f"`{json.dumps(node['default'])}`"
    if "x-default" in node:
        return str(node["x-default"])
    return "none"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _rows(
    node: dict[str, Any], defs: dict[str, Any], prefix: str
) -> list[tuple[str, dict[str, Any], bool]]:
    rows: list[tuple[str, dict[str, Any], bool]] = []
    required = set(node.get("required", ()))
    for key, child in node.get("properties", {}).items():
        child = _resolve(child, defs)
        path = f"{prefix}{key}"
        rows.append((path, child, key in required))
        rows += _rows(child, defs, f"{path}.")
    extra = node.get("additionalProperties")
    if isinstance(extra, dict):
        rows += _rows(_resolve(extra, defs), defs, f"{prefix}<name>.")
    return rows


def render(schema: dict[str, Any]) -> str:
    """The markdown block (markers included) for `schema`."""
    defs = schema.get("$defs", {})
    lines = [
        BEGIN,
        "",
        "| Key | Type | Default | Meaning |",
        "| --- | --- | --- | --- |",
    ]
    for path, node, required in _rows(schema, defs, ""):
        lines.append(
            f"| `{path}` | {_type(node)} | {_cell(_default(node, required))} "
            f"| {_cell(node.get('description', ''))} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def splice(guide: str, block: str) -> str:
    """Replace the marked block in `guide`. Raises ValueError if the markers are missing."""
    start = guide.find(BEGIN)
    end = guide.find(END)
    if start < 0 or end < start:
        raise ValueError(f"markers not found; the guide must contain {BEGIN!r} and {END!r}")
    return guide[:start] + block + guide[end + len(END) :]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the guide is stale")
    parser.add_argument("--guide", type=Path, default=GUIDE)
    args = parser.parse_args(argv)
    guide_path: Path = args.guide
    current = guide_path.read_text(encoding="utf-8")
    try:
        updated = splice(current, render(json.loads(SCHEMA.read_text(encoding="utf-8"))))
    except ValueError as exc:
        print(f"error: {guide_path}: {exc}", file=sys.stderr)
        return 2
    if updated == current:
        print(f"{guide_path}: config reference up to date")
        return 0
    if args.check:
        print(
            f"error: {guide_path}: config reference is stale; run "
            "`uv run python scripts/gen_config_reference.py`",
            file=sys.stderr,
        )
        return 1
    guide_path.write_text(updated, encoding="utf-8")
    print(f"{guide_path}: config reference updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
